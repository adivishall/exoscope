"""Offline copies of real light curves bundled with ExoScope.

Generated by ``scripts/fetch_samples.py`` from MAST. They are real Kepler/TESS
observations; the app labels them "offline copy" so it is clear the data were
not freshly downloaded.
"""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

from .model import DataError, LightCurveData

SAMPLES_DIR = Path(__file__).resolve().parent / "samples"


def list_samples() -> list[dict]:
    """Return metadata for every bundled sample (sorted by id)."""
    out = []
    for meta_path in sorted(SAMPLES_DIR.glob("*.json")):
        meta = json.loads(meta_path.read_text())
        meta["sample_id"] = meta_path.stem
        out.append(meta)
    return out


def load_sample(sample_id: str) -> LightCurveData:
    if not sample_id.replace("_", "").isalnum():
        raise ValueError(f"Invalid sample id: {sample_id!r}")
    csv_path = SAMPLES_DIR / f"{sample_id}.csv.gz"
    meta_path = SAMPLES_DIR / f"{sample_id}.json"
    if not csv_path.exists() or not meta_path.exists():
        raise DataError(f"Bundled sample '{sample_id}' not found. Run scripts/fetch_samples.py to create it.")
    meta = json.loads(meta_path.read_text())
    meta["source"] = "bundled"
    meta["sample_id"] = sample_id
    return LightCurveData.from_frame(pd.read_csv(csv_path), meta)
